async function importarInsumosMasivos() {
    console.log("Iniciando la carga de materias primas a Firebase...");
    for (const item of insumosParaSubir) {
        try {
            await addDoc(collection(db, "materiaPrima"), {
                nombre: item.nombre,
                precio: Number(item.precio),
                cantidad: Number(item.cantidad),
                stock: Number(item.stock)
            });
            console.log("✅ Materia prima guardada:", item.nombre);
        } catch (e) {
            console.error("❌ Error al guardar:", item.nombre, e);
        }
    }
    console.log("🎉 ¡Carga masiva de materias primas finalizada con éxito!");
}

// Expone la función para ejecutarla desde la consola del navegador (F12)
window.importarInsumos = importarInsumosMasivos;